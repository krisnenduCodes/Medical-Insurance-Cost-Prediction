import streamlit as st
import pandas as pd
import joblib

# ----------------------------------
# 1. Page Configuration
# ----------------------------------

st.set_page_config(
    page_title="Medical Insurance Cost Prediction",
    page_icon="🏥",
    layout="centered"
)

# ----------------------------------
# 2. Load Trained Model
# ----------------------------------

@st.cache_resource
def load_model():
    return joblib.load("models/final_insurance_model.pkl")

model = load_model()


# ----------------------------------
# 3. Application Title
# ----------------------------------

st.title("🏥 Medical Insurance Cost Prediction")

st.write(
    "Enter your personal details to estimate your medical insurance charges."
)

st.divider()


# ----------------------------------
# 4. User Input
# ----------------------------------

st.subheader("Enter Your Details")

age = st.number_input(
    "Age",
    min_value=18,
    max_value=100,
    value=25
)

sex = st.selectbox(
    "Gender",
    ["male", "female"]
)

bmi = st.number_input(
    "BMI",
    min_value=10.0,
    max_value=60.0,
    value=25.0,
    step=0.1
)

children = st.number_input(
    "Number of Children",
    min_value=0,
    max_value=10,
    value=0
)

smoker = st.selectbox(
    "Smoking Status",
    ["yes", "no"]
)

region = st.selectbox(
    "Region",
    ["southeast", "southwest", "northeast", "northwest"]
)


# ----------------------------------
# 5. Prediction
# ----------------------------------

if st.button("Predict Insurance Cost", use_container_width=True):

    # Convert smoking status into a temporary numerical value
    smoker_value = 1 if smoker == "yes" else 0

    # Create interaction features
    age_smoker = age * smoker_value
    bmi_smoker = bmi * smoker_value

    # Create input DataFrame
    input_data = pd.DataFrame({

        "age": [age],
        "sex": [sex],
        "bmi": [bmi],
        "children": [children],
        "smoker": [smoker],
        "region": [region],
        "age_smoker": [age_smoker],
        "bmi_smoker": [bmi_smoker]

    })

    # Make prediction
    prediction = model.predict(input_data)

    # Display result
    st.success("Prediction completed successfully!")

    st.subheader("Estimated Medical Insurance Cost")

    st.metric(
        label="Predicted Insurance Charges",
        value=f"${prediction[0]:,.2f}"
    )

    st.caption(
        "This is an estimated value generated by a machine learning model, "
        "not an actual insurance quotation."
    )